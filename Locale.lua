--  Строки интерфейса в коде написаны по-русски и проходят через ns.T().
--  Для английского T() берёт перевод из ns.EN, названия и описания готовых
--  макросов - из ns.EN_MACROS["КЛАСС/русское имя"]. Тексты самих макросов
--  от языка не зависят: заклинания в них записаны по ID.
--  Язык выбирается в настройках MacroCoach («Авто» - язык клиента) и
--  меняется после перезагрузки интерфейса. Выбор хранится в MacroCoachDB,
--  а он загружается после файлов аддона: до ADDON_LOADED язык - язык
--  клиента, поэтому переводить строки при загрузке файлов нельзя.
-------------------------------------------------------------------------------
