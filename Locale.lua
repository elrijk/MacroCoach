-- Готовые переводы. Остальные языки в списке серые. Русский и английский
-- - здесь же, остальные - в файлах Locales\*.lua: ns.LOCALES[код] -
-- функция, которая строит таблицу «английская строка -> перевод». Строится
-- только выбранный язык (ns.SetLang), остальные отдаются сборщику мусора.
ns.READY = { enUS = true, ruRU = true }
ns.LOCALES = {}

local function Ready(code)
  return ns.READY[code] or ns.LOCALES[code] ~= nil or (code == "esMX" and ns.LOCALES.esES ~= nil)
end

-- Выбор из настроек -> язык. «Авто»: язык клиента, если перевод готов,
-- иначе английский.
function ns.ResolveLang(choice)
  if choice and choice ~= "auto" and Ready(choice) then return choice end
  local client = GetLocale and GetLocale() or "enUS"
  if client == "enGB" then client = "enUS" end
  return Ready(client) and client or "enUS"
end

-- До ADDON_LOADED - язык клиента, на нём - выбранный в настройках.
ns.lang = ns.ResolveLang(nil)

function ns.SetLang(choice)
  ns.lang = ns.ResolveLang(choice)
  if ns.langSet then return end
  ns.langSet = true
  for code in pairs(ns.LOCALES) do ns.READY[code] = true end
  if ns.LOCALES.esES then ns.READY.esMX = true end
  local make = ns.LOCALES[ns.lang] or (ns.lang == "esMX" and ns.LOCALES.esES)
  ns.L = make and make() or nil
  for code in pairs(ns.LOCALES) do ns.LOCALES[code] = nil end
end

-- Строка на выбранном языке: русская как есть, иначе английская из ns.EN
-- и её перевод из ns.L (если язык не английский).
function ns.T(s)
  if s == nil or ns.lang == "ruRU" then return s end
  local en = ns.EN[s] or s
  local L = ns.L
  return L and L[en] or en
end

-- Перевод английского текста (данные, у которых есть только ruRU и enUS).
function ns.TE(s)
  local L = ns.L
  return L and s and L[s] or s
end

-- Таблица данных на выбранном языке: своя (ruRU, enUS) или английская,
-- переведённая через ns.L (копия, строится один раз).
local function Translate(v)
  if type(v) == "string" then return ns.L[v] or v end
  if type(v) ~= "table" then return v end
  local out = {}
  for k, x in pairs(v) do out[k] = Translate(x) end
  return out
end
local picked = setmetatable({}, { __mode = "k" })
function ns.Pick(t)
  if not t then return nil end
  local own = t[ns.lang]
  if own then return own end
  if not ns.L or t.enUS == nil then return t.enUS end
  local c = picked[t]
  if c == nil then c = Translate(t.enUS); picked[t] = c end
  return c
end

